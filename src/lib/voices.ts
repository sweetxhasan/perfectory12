export type LanguageId = 'en' | 'bn' | 'hi';
export type VoicePlan = 'free' | 'monthly' | 'yearly';

/** Voice returned by the remote API */
export interface ApiVoice {
  voice_id: string;
  name: string;
  character_type: 'male' | 'female';
  voice_type: string; // "free" | "pro" | "pro_max" | …
  profile_photo_url: string | null;
  play_audio_url: string | null;
  /** Mapped from voice_type */
  plan: VoicePlan;
  /** Alias of character_type */
  gender: 'male' | 'female';
}

function mapVoiceType(type: string): VoicePlan {
  if (type === 'free') return 'free';
  if (type === 'pro') return 'monthly';
  return 'yearly'; // pro_max, premium, etc.
}

export async function fetchVoices(): Promise<ApiVoice[]> {
  const res = await fetch('https://gsvtcpiwxaslgusfmzok.supabase.co/functions/v1/voice-list');
  if (!res.ok) throw new Error(`Voice list fetch failed: ${res.status}`);
  const json = await res.json();
  const data: Array<{
    name: string;
    voice_id: string;
    character_type: 'male' | 'female';
    voice_type: string;
    profile_photo_url: string | null;
    play_audio_url: string | null;
  }> = json.data ?? [];
  return data.map((v) => ({
    ...v,
    plan: mapVoiceType(v.voice_type),
    gender: v.character_type,
  }));
}

