export type PlanId = 'free' | 'monthly' | 'yearly';
const PLAN_RANK: Record<PlanId, number> = { free: 0, monthly: 1, yearly: 2 };

export function canUseVoice(userPlan: PlanId, voicePlan: VoicePlan): boolean {
  return PLAN_RANK[userPlan] >= PLAN_RANK[voicePlan];
}

/** Each generation costs exactly 1 credit, regardless of length. */
export function creditCost(_text: string): number {
  return 1;
}

export function speakText(
  text: string,
  language: Language,
  voice: Voice,
  onEnd?: () => void,
  onError?: (msg: string) => void,
): SpeechSynthesisUtterance | null {
  if (!('speechSynthesis' in window)) {
    onError?.('Your browser does not support speech synthesis.');
    return null;
  }
  window.speechSynthesis.cancel();

  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang   = language.lang;
  utterance.rate   = voice.rate;
  utterance.pitch  = voice.pitch;
  utterance.volume = 1;

  const voices = window.speechSynthesis.getVoices();
  const match =
    voices.find((v) => v.lang === language.lang) ??
    voices.find((v) => v.lang.startsWith(language.lang.split('-')[0]));
  if (match) utterance.voice = match;

  utterance.onend  = () => onEnd?.();
  utterance.onerror = (e) => {
    if (e.error !== 'interrupted') onError?.(`Speech error: ${e.error}`);
  };

  window.speechSynthesis.speak(utterance);
  return utterance;
}

/** Split text into ≤200-char chunks on word boundaries for TTS download */
export function chunkText(text: string, maxLen = 200): string[] {
  const chunks: string[] = [];
  let remaining = text.trim();
  while (remaining.length > maxLen) {
    let cut = remaining.lastIndexOf(' ', maxLen);
    if (cut < 10) cut = maxLen;
    chunks.push(remaining.slice(0, cut).trim());
    remaining = remaining.slice(cut).trim();
  }
  if (remaining) chunks.push(remaining);
  return chunks;
}
